import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const legal = {};
for (const [key, file] of [['terms', 'user-agreement.md'], ['privacy', 'privacy-policy.md']]) {
  const text = fs.readFileSync(path.join(root, 'docs/mvp', file), 'utf8');
  const lines = text.trim().split(/\r?\n/);
  legal[key] = { title: lines[0].replace(/^# /, ''), version: 'V0.3', paragraphs: lines.slice(1).map(line => line.trim()).filter(Boolean) };
}
fs.mkdirSync(path.join(root, 'preview/shared'), { recursive: true });
fs.writeFileSync(path.join(root, 'preview/shared/legal-content.js'), `// Generated by scripts/build-preview-legal.mjs from docs/mvp; do not edit.\nwindow.FRIDGE_LEGAL = ${JSON.stringify(legal, null, 2)};\n`);
console.log('Built shared V0.3 legal content for App and website preview.');
