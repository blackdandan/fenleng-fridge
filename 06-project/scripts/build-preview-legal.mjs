import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const legal = {};
const miniLegal = {};
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
function htmlFor(text) {
  let table = false;
  const body = [];
  for (const raw of text.trim().split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('|')) {
      const cells = line.split('|').slice(1, -1).map(value => value.trim());
      if (cells.every(cell => /^:?-+:?$/.test(cell))) continue;
      const tag = table ? 'td' : 'th';
      if (!table) {body.push('<div class="table"><table>'); table = true;}
      body.push('<tr>' + cells.map(cell => `<${tag}>${escape(cell)}</${tag}>`).join('') + '</tr>');
      continue;
    }
    if (table) {body.push('</table></div>'); table = false;}
    const heading = line.match(/^(#{1,3}) (.*)$/);
    body.push(heading ? `<h${heading[1].length}>${escape(heading[2])}</h${heading[1].length}>` : `<p>${escape(line)}</p>`);
  }
  if (table) body.push('</table></div>');
  return `<!doctype html><html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'"><style>
:root{color-scheme:light dark}body{margin:0;padding:24px;background:#fffffa;color:#2c3c32;font:17px/1.8 system-ui,sans-serif;overflow-wrap:anywhere}main{max-width:680px;margin:auto}h1{font-size:26px;line-height:1.4}h2{font-size:21px;margin-top:32px}p{white-space:pre-wrap}.table{overflow-x:auto}table{border-collapse:collapse;min-width:460px;font-size:15px}th,td{border:1px solid #e4e8df;text-align:start;padding:10px;vertical-align:top}@media(prefers-color-scheme:dark){body{background:#19231d;color:#e0e6dc}th,td{border-color:#435047}}
</style></head><body><main>${body.join('\n')}</main></body></html>\n`;
}
for (const [key, file] of [['terms', 'user-agreement.md'], ['privacy', 'privacy-policy.md']]) {
  const text = fs.readFileSync(path.join(root, '01-product/mvp', file), 'utf8');
  const lines = text.trim().split(/\r?\n/);
  const version = text.match(/版本：[^\n]*\/ (V[\d.]+)/)?.[1];
  if (!version) throw new Error(`Missing legal version: ${file}`);
  legal[key] = { title: lines[0].replace(/^# /, ''), version, paragraphs: lines.slice(1).map(line => line.trim()).filter(Boolean) };
  const assets = path.join(root, '06-project/app/apps/fridge/assets/legal');
  fs.mkdirSync(assets, {recursive:true});
  fs.writeFileSync(path.join(assets, `${key}.md`), text);
  const html = htmlFor(text);
  fs.writeFileSync(path.join(assets, `${key}.html`), html);
  miniLegal[key] = {title: legal[key].title, version, html: html.match(/<main>([\s\S]*)<\/main>/)[1]};
}
fs.mkdirSync(path.join(root, '06-project/prototype/shared'), { recursive: true });
fs.writeFileSync(path.join(root, '06-project/prototype/shared/legal-content.js'), `// Generated by 06-project/scripts/build-preview-legal.mjs from 01-product/mvp; do not edit.\nwindow.FRIDGE_LEGAL = ${JSON.stringify(legal, null, 2)};\n`);
const miniDirectory = path.join(root, '06-project/mini-program/apps/miniapp/src/legal');
fs.mkdirSync(miniDirectory, {recursive:true});
fs.writeFileSync(path.join(miniDirectory, 'documents.json'), JSON.stringify(miniLegal, null, 2) + '\n');
console.log('Built shared legal content and offline App WebView HTML from product documents.');
